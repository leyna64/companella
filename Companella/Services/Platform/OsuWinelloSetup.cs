using Companella.Services.Common;

namespace Companella.Services.Platform;

/// <summary>
/// One-time setup for running Companella! next to osu! on Linux through osu-winello (--osu-winello).
/// Must be run inside the osu-winello Wine prefix via <c>osu-wine --wine</c>.
/// </summary>
public static class OsuWinelloSetup
{
	/// <summary>
	/// Command line flag that triggers the setup.
	/// </summary>
	public const string Flag = "--osu-winello";

	/// <summary>
	/// Writes a Linux launcher script and app menu entry that start osu! (through osu-wine) and then Companella!
	/// in the same Wine prefix, and enables osu-winello mode in the user settings.
	/// </summary>
	/// <returns>Process exit code: 0 on success, 1 on failure.</returns>
	public static int Run()
	{
		try
		{
			// Both are exported by osu-wine, so they are only present when started through `osu-wine --wine`
			var dataHome = Environment.GetEnvironmentVariable("XDG_DATA_HOME");
			var binDir = Environment.GetEnvironmentVariable("BINDIR");
			if (string.IsNullOrEmpty(dataHome) || string.IsNullOrEmpty(binDir))
			{
				Report("osu-wine environment not found. Run: osu-wine --wine 'C:\\users\\<you>\\AppData\\Local\\Companella\\Companella!.exe' --osu-winello");
				return 1;
			}

			// Squirrel's stub in the install root survives updates; app-x.y.z\ does not
			var appDir = AppContext.BaseDirectory.TrimEnd('\\');
			var installDir = Path.GetDirectoryName(appDir) ?? appDir;
			var stubExe = Path.Combine(installDir, "Companella!.exe");
			var companellaExe = File.Exists(stubExe) ? stubExe : Environment.ProcessPath!;

			// Squirrel cannot check for updates in-app while osu! runs under Wine, so update before osu! starts
			var updateExe = Path.Combine(installDir, "Update.exe");
			var updateCommand = File.Exists(updateExe)
				? $"'{binDir}/osu-wine' --wine '{updateExe}' --update '{SquirrelUpdaterService.UpdateUrl}' >/dev/null 2>&1"
				: string.Empty;

			var scriptPath = $"{dataHome}/companella/osu-winello.sh";
			var desktopPath = $"{dataHome}/applications/companella-osu-winello.desktop";

			var script = $$"""
				#!/usr/bin/env bash
				# Generated by Companella! {{Flag}}. Starts osu! through osu-wine when it is not running,
				# then Companella! in the same Wine prefix (osu-wine restarts Wine if osu! is not running yet).
				pgrep -x 'osu!.exe' >/dev/null || {
					{{updateCommand}}
					'{{binDir}}/osu-wine' >/dev/null 2>&1 &
					for _ in $(seq 60); do pgrep -x 'osu!.exe' >/dev/null && break; sleep 1; done
				}
				pgrep -x 'Companella!.exe' >/dev/null || exec '{{binDir}}/osu-wine' --wine '{{companellaExe}}'
				""";

			var desktop = $"""
				[Desktop Entry]
				Type=Application
				Name=Companella! (osu-winello)
				Comment=Start osu! and Companella! through osu-winello
				Exec=bash "{scriptPath}"
				Terminal=false
				Categories=Game;
				""";

			WriteUnixFile(scriptPath, script);
			WriteUnixFile(desktopPath, desktop);

			var settingsService = new UserSettingsService();
			settingsService.InitializeAsync().GetAwaiter().GetResult();
			settingsService.Settings.OsuWinello = true;
			settingsService.SaveAsync().GetAwaiter().GetResult();

			Report($"osu-winello setup done. Start \"Companella! (osu-winello)\" from your app menu, or run: bash {scriptPath}");
			return 0;
		}
		catch (Exception ex)
		{
			Report($"osu-winello setup failed: {ex.Message}");
			return 1;
		}
	}

	/// <summary>
	/// Writes a file to a Linux path with LF line endings.
	/// </summary>
	private static void WriteUnixFile(string unixPath, string content)
	{
		// shortcut: assumes Wine's default Z: -> / drive mapping (osu-winello keeps it), use winepath if a prefix lacks it
		var windowsPath = "Z:" + unixPath.Replace('/', '\\');
		Directory.CreateDirectory(Path.GetDirectoryName(windowsPath)!);
		File.WriteAllText(windowsPath, content.ReplaceLineEndings("\n") + "\n");
	}

	private static void Report(string message)
	{
		Logger.Info($"[osu-winello] {message}");
		Console.WriteLine(message);
	}
}
